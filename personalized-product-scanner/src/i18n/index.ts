/**
 * Simple helper to retrieve translated strings
 */
export function getTranslation(lang: SupportedLanguage, key: string, fallback?: string): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const aliasKey = KEY_ALIAS_MAP[key];

  if (dict && dict[key]) return dict[key];
  if (dict && aliasKey && dict[aliasKey]) return dict[aliasKey];
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
  if (TRANSLATIONS.en && aliasKey && TRANSLATIONS.en[aliasKey]) return TRANSLATIONS.en[aliasKey];

  return fallback || key;
}
